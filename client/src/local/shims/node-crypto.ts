/**
 * The slice of `node:crypto` the server uses: random session tokens and SHA-256.
 * Backed by WebCrypto, which is available in the WebView's worker scope.
 *
 * createHash() is synchronous in Node; WebCrypto's digest is not, so this uses a
 * small self-contained SHA-256 implementation. Session-token hashing sits on the
 * login path and must stay synchronous for the transaction rules to hold.
 */

function toHex(bytes: Uint8Array): string {
  let out = '';
  for (const byte of bytes) out += byte.toString(16).padStart(2, '0');
  return out;
}

function toBase64(bytes: Uint8Array): string {
  let binary = '';
  for (const byte of bytes) binary += String.fromCharCode(byte);
  return btoa(binary);
}

export class ByteBuffer {
  constructor(readonly bytes: Uint8Array) {}
  toString(encoding: 'hex' | 'base64' | 'utf8' = 'hex'): string {
    if (encoding === 'hex') return toHex(this.bytes);
    if (encoding === 'base64') return toBase64(this.bytes);
    return new TextDecoder().decode(this.bytes);
  }
}

export function randomBytes(size: number): ByteBuffer {
  const bytes = new Uint8Array(size);
  crypto.getRandomValues(bytes);
  return new ByteBuffer(bytes);
}

export function randomUUID(): string {
  return crypto.randomUUID();
}

